export interface CategoryBreakdown {
  categoria: string;
  interacoes: number;
  servicos: number;
}

export interface MonthlyPoint {
  mes: string;       // "Mar/2025"
  interacoes: number;
  compartilhadas: number;
}

export interface EstadoData {
  uf: string;
  estado: string;
  regiao: string;
  advogados: number;        // Total de advogados ativos (OAB)
  totalInteracoes: number;  // Total de interações últimos 12 meses
  interacoesCompartilhadas: number;
  interacoesPer1000: number; // Normalizado por 1.000 advogados
  categorias: CategoryBreakdown[];
  tendencia: 'alta' | 'estavel' | 'baixa';
  ultimaAtualizacao: string;
  fontesPrincipais: string[];
  historicoMensal: MonthlyPoint[];
}

const MONTHS_12 = [
  'Mar/2024', 'Abr/2024', 'Mai/2024', 'Jun/2024',
  'Jul/2024', 'Ago/2024', 'Set/2024', 'Out/2024',
  'Nov/2024', 'Dez/2024', 'Jan/2025', 'Fev/2025',
];

// Simple deterministic pseudo-random based on index to avoid flickering
function deterministicFactor(seed: number): number {
  const x = Math.sin(seed + 1) * 10000;
  return 0.9 + (x - Math.floor(x)) * 0.2;
}

function monthlyHistory(base: number, growthRate: number): MonthlyPoint[] {
  return MONTHS_12.map((mes, i) => {
    const factor = 1 + growthRate * (i / 11);
    const interacoes = Math.round(base * factor * deterministicFactor(base * 100 + i));
    return { mes, interacoes, compartilhadas: Math.round(interacoes * 0.35) };
  });
}

